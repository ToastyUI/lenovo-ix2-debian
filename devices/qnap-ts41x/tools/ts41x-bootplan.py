#!/usr/bin/env python3
"""Generate the U-Boot env changes for booting Debian (USB and/or disk) with a QTS fallback.

Every stage writes a changes file in fw_setenv -s format (name=value), which you
apply to an mtd4 dump with qnap-uboot-env.py on a PC, or with fw_setenv -s on Debian.

  stage1  probe: proves U-Boot's saveenv persists, then boots QTS exactly as before.
  stage2  arm:   next boot tries Debian once; any failure (or a hang + power cycle) = QTS.
  restore        puts bootcmd/bootargs back to the stock values saved in stage1.

  ts41x-bootplan.py stage1 --env mtd4.bin -o stage1.txt
  ts41x-bootplan.py stage2 --env mtd4.bin --lba 0x1035a8 [--pic-led] -o stage2.txt
  ts41x-bootplan.py stage2 --env mtd4.bin --disk-ext2 0:1 -o stage2.txt
  ts41x-bootplan.py stage2 --env mtd4.bin --lba 0x1035a8 -o stage2.txt

Sources, tried in the order given, then QTS from flash:
  --disk-ext2 DEV:PART  ext2load /boot.uimg from an ext2 partition on a SATA disk
  --lba 0x...           ide read of a raw area written by ts41x-install-boot.sh
  --usb                 ext2load from USB -- NOT on the stock TS-41x U-Boot, which has no
                        usb command (GPL source, docs/uboot-analysis.md); custom U-Boot only
On stock hardware use --disk-ext2 (cleanest) or --lba.

How the one-shot guard works (stage2):
  bootcmd=run bootcmd_debian
  bootcmd_debian first sets bootcmd back to "run bootcmd_fallback" and runs saveenv,
  THEN tries each source and runs bootm. If bootm returns (no stick, no disk, bad CRC)
  the next source is tried, and finally QTS in the same boot. If Debian hangs, the next power
  cycle boots QTS, because the env already says so. Only Debian itself re-arms
  (ts41x-boot-ok.service, after a complete boot).
"""
import argparse
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("qenv", os.path.join(HERE, "qnap-uboot-env.py"))
qenv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(qenv)

LOAD_ADDR = "0x800000"     # multi-image is read here; ends below 0x3800000 (48 MiB area)
AREA_SECTORS = "0x18000"   # 48 MiB, must match tools/ts41x-install-boot.sh
# Debian cmdline. Kept short on purpose: old U-Boot rejects or truncates command lines longer
# than its console buffer (often 256 bytes), so every executed variable stays under MAX_CMD.
# (The U-Boot flash partition is made read-only in the DTB instead, see ts41x-mkimage.)
DEBIAN_ARGS = "console=ttyS0,115200 root=LABEL=rootfs rootdelay=10 panic=10"
MAX_CMD = 200
STOCK_PATTERN = re.compile(r"cp\.[bl] 0xf82\d+ 0x800000 .*bootm 0x800000")

LED_TRYING = "uart1 0x58; "  # status LED green/red alternating 2 Hz while U-Boot tries Debian


def write(path, lines):
    with open(path, "w") as fh:
        fh.write("# generated by ts41x-bootplan.py - review before applying\n")
        for k, v in lines:
            if v is not None and "\n" in v:
                sys.exit(f"newline in value of {k}")
            fh.write(f"{k}={v}\n" if v is not None else f"{k}\n")
    print(f"wrote {path}", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stage", choices=["stage1", "stage2", "restore"])
    ap.add_argument("--env", required=True, help="raw dump of mtd4 (U-Boot Config)")
    ap.add_argument("--lba", help="raw disk boot area, first sector (from ts412-analyze.py / ts41x-install-boot.sh)")
    ap.add_argument("--disk-ext2", metavar="DEV:PART",
                    help="ext2load /boot.uimg from an ext2 partition on a SATA disk, e.g. 0:1 (ide dev:part)")
    ap.add_argument("--usb", action="store_true",
                    help="try /boot.uimg from USB first. NOTE: the stock TS-41x U-Boot has no 'usb' command "
                         "(GPL source, docs/uboot-analysis.md), so this only works on a reflashed/custom U-Boot.")
    ap.add_argument("--pic-led", action="store_true", help="add uart1 LED feedback (only if the analyzer found uart1)")
    ap.add_argument("--force", action="store_true", help="accept a bootcmd that does not look stock")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()

    _, _, env, _ = qenv.load(a.env, None)
    out = []
    if a.stage == "stage1":
        if "bootcmd_stock" in env and not a.force:
            sys.exit("bootcmd_stock already exists: stage1 was applied before (use the existing values)")
        stock = env.get("bootcmd", "")
        if not STOCK_PATTERN.search(stock) and not a.force:
            sys.exit(f"bootcmd does not look like the stock flash boot:\n  {stock}\nrefusing (use --force after checking)")
        out += [("bootcmd_stock", stock),
                ("bootargs_stock", env.get("bootargs", "")),
                ("ts_probe_saveenv", "pending"),
                ("bootcmd", "setenv ts_probe_saveenv ok; setenv bootcmd run bootcmd_stock; saveenv; run bootcmd_stock")]
    elif a.stage == "stage2":
        for need in ("bootcmd_stock", "bootargs_stock"):
            if need not in env:
                sys.exit(f"{need} missing: apply stage1 first")
        if env.get("ts_probe_saveenv") != "ok" and not a.force:
            sys.exit(f"ts_probe_saveenv={env.get('ts_probe_saveenv')!r}: saveenv not proven to persist; "
                     "without it the one-shot guard does not work. Stop here.")
        if not a.usb and not a.lba and not a.disk_ext2:
            sys.exit("give at least one source: --disk-ext2 DEV:PART, --lba 0x..., or --usb")
        if a.usb:
            print("WARNING: the stock TS-41x U-Boot has no 'usb' command (see docs/uboot-analysis.md).\n"
                  "         --usb only works on a reflashed/custom U-Boot. Use --disk-ext2 or --lba on stock.",
                  file=sys.stderr)
        if a.disk_ext2 and not re.fullmatch(r"\d+:\d+", a.disk_ext2):
            sys.exit("--disk-ext2 must be DEV:PART, e.g. 0:1")
        if a.lba and not re.fullmatch(r"0x[0-9a-fA-F]+", a.lba):
            sys.exit("--lba must be hex, as printed by the analyzer/installer (e.g. 0x1035a8)")
        if a.lba and int(a.lba, 16) >= 1 << 28:
            sys.exit("boot area beyond LBA28 (128 GiB): old U-Boot IDE code may not reach it")
        led = LED_TRYING if a.pic_led else ""
        chain = ["setenv bootcmd run bootcmd_fallback", "saveenv"] + ([led.strip("; ")] if led else [])
        out += [("bootcmd_fallback", "setenv bootargs $(bootargs_stock); run bootcmd_stock"),
                ("ts_boot", f"setenv bootargs {DEBIAN_ARGS}; bootm {LOAD_ADDR}")]
        if a.usb:
            # usb stop afterwards: leave the controller as QTS expects it if we fall through
            out.append(("ts_usb", f"usb reset; mw {LOAD_ADDR} 0 1; ext2load usb 0:1 {LOAD_ADDR} /boot.uimg; "
                                  "run ts_boot; usb stop"))
            chain.append("run ts_usb")
        if a.disk_ext2:
            out.append(("ts_ext2", f"ide reset; mw {LOAD_ADDR} 0 1; ext2load ide {a.disk_ext2} {LOAD_ADDR} /boot.uimg; "
                                   "run ts_boot"))
            chain.append("run ts_ext2")
        if a.lba:
            out.append(("ts_hdd", f"ide reset; mw {LOAD_ADDR} 0 1; ide read {LOAD_ADDR} {a.lba[2:]} {AREA_SECTORS[2:]}; "
                                  "run ts_boot"))
            out.append(("ts_boot_lba", a.lba))
            chain.append("run ts_hdd")
        chain.append("run bootcmd_fallback")
        out += [("bootcmd_debian", "; ".join(chain)),
                ("ts_probe_saveenv", None),
                ("bootcmd", "run bootcmd_debian")]
    else:  # restore
        for need in ("bootcmd_stock", "bootargs_stock"):
            if need not in env:
                sys.exit(f"{need} missing: nothing to restore from")
        out += [("bootcmd", env["bootcmd_stock"]), ("bootargs", env["bootargs_stock"])]
        out += [(k, None) for k in ("bootcmd_fallback", "bootcmd_debian", "ts_usb", "ts_ext2", "ts_hdd", "ts_boot",
                                    "ts_boot_lba", "ts_probe_saveenv",
                                    "ts_last_ok", "bootcmd_stock", "bootargs_stock")]
    for k, v in out:
        if v is not None and (k.startswith("bootcmd") or k in ("ts_usb", "ts_ext2", "ts_hdd", "ts_boot")) and len(v) > MAX_CMD:
            sys.exit(f"{k} is {len(v)} chars; keep executed commands under {MAX_CMD} for old U-Boot")
    write(a.output, out)


if __name__ == "__main__":
    main()
